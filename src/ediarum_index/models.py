"""SQLModel table definitions and the request/response (I/O) models.

Single-table design: every entry type shares the ``entry`` table and keeps its
type-specific values in the JSON ``data`` bag (described by the schema layer in
``schemas.py`` / ``projects/``). ``project_name`` and ``entry_type`` are foreign
keys into the ``project`` and ``entry_type`` lookup tables, which
``bootstrap.sync_registry`` fills on startup (entry types from code, projects
from the platform registry).

Naming convention (as in SQLModel's tutorial): ``<X>Base`` holds shared columns,
``<X>`` (``table=True``) is the table, ``<X>Create`` / ``<X>Update`` /
``<X>Public`` are the API-facing shapes.

Every table sets ``__table_args__ = {"mysql_charset": "utf8mb4"}`` — plain
``alembic revision --autogenerate`` never emits that kwarg on its own, so
without it here a future autogenerated migration would silently drop it.
"""

from datetime import datetime, timezone
from typing import Literal
from ediarum_sdk.auth import ApiKey  # noqa: F401 — the SDK's `sdk_api_key` table, registered for migrations
from sqlalchemy import Text, UniqueConstraint
from sqlmodel import SQLModel, Field, Column, JSON, Relationship

