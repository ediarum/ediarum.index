class Relation(SQLModel, table=True):
    """Generic (subject, predicate, object) triple linking two entries.

    Unique on the full triple — an ingest run (or anyone else) re-creating the
    same relation gets a 409 (see ``services.create_relation``), not a duplicate row.
    """

    __table_args__ = (
        UniqueConstraint("subject_id", "predicate", "object_id", name="uq_relation_triple"),
        {"mysql_charset": "utf8mb4"},
    )
    id: int | None = Field(default=None, primary_key=True)
    subject_id: int = Field(foreign_key="entry.id", index=True)
    predicate: str = Field(max_length=128, index=True)
    object_id: int = Field(foreign_key="entry.id", index=True)

class RelationCreate(SQLModel):
    subject_id: int
    predicate: str = Field(max_length=128)
    object_id: int

class RelationPublic(SQLModel):
    id: int
    subject_id: int
    predicate: str
    object_id: int

class RelationWithLabels(RelationPublic):
    """``GET /{project}/relations``' response shape — adds the subject's and object's
    own ``label``, resolved server-side (one join, not per-row), so a caller
    never has to turn a bare id into a display string itself. `POST`/`DELETE`
    return the plain ``RelationPublic``: the caller that just created a
    relation already has both labels client-side."""

    subject_label: str
    object_label: str

class MentionAnchor(SQLModel, table=True):
    """The exact character span a ``mentions`` `Relation`'s link occupied
    inside its subject entry's own ``note`` text, as of the ingest run
    that found it — lets export splice the link back in at that exact
    position instead of re-deriving placement by searching for the
    target's name in the flattened text (see ``export._emit_mentions``).

    Deliberately not columns on `Relation` itself: `Relation` is a
    generic, project-agnostic triple table shared by every predicate
    (``member_of``, ``part_of``, ``mentions``, ...), and this data only
    ever makes sense for ``mentions``. One row per relation
    (``relation_id`` unique) — a name mentioned twice in one note still
    only gets one ``mentions`` relation
    (``ingest._reconcile_relations_multi``'s dedup), so only one anchor
    makes sense either way.

    Lazily self-validating, not actively kept in sync on edit: export
    compares ``captured_text`` against the subject's *current*
    ``data["note"]`` at ``[start_offset:end_offset]`` — if they still
    match, the anchor is trusted; if a curator has edited that part of
    the note since ingest, they won't, and export silently falls back to
    the search-based placement instead. No edit-tracking
    machinery is needed on the write path for this reason — a stale
    anchor is simply ignored at read time, never actively invalidated.
    """

    __tablename__ = "mention_anchor"
    __table_args__ = {"mysql_charset": "utf8mb4"}
    id: int | None = Field(default=None, primary_key=True)
    relation_id: int = Field(foreign_key="relation.id", unique=True, index=True)
    start_offset: int
    end_offset: int
    captured_text: str = Field(sa_column=Column(Text, nullable=False))

class MentionAnchorUpsert(SQLModel):
    start_offset: int
    end_offset: int
    captured_text: str

class MentionAnchorPublic(SQLModel):
    id: int
    relation_id: int
    start_offset: int
    end_offset: int
    captured_text: str

class IngestRun(SQLModel, table=True):
    """One ``ingest.py`` run against one profile slug (see ``ingest.PROFILES``).

    Persists the run's summary (created/updated/unchanged counts,
    conflict/skipped/failed details) so a run the watcher starts, with nobody
    at a terminal, surfaces its problems in the app. Written once, at the
    end of a run, by ``ingest.py``'s own ``report_run``; never updated after.
    """

    __tablename__ = "ingest_run"
    __table_args__ = {"mysql_charset": "utf8mb4"}
    id: int | None = Field(default=None, primary_key=True)
    project: str = Field(max_length=128, index=True)  # the profile slug, e.g. "schleiermacher_persons"
    started_at: datetime
    finished_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    status: str = Field(max_length=16)  # "ok" | "conflicts" | "failed"
    created: int
    updated: int
    unchanged: int
    # one dict per conflict/skipped/failed record: {"fname", "ext_id", "detail",
    # "kind"} with kind in {"conflict", "skipped", "failed"} — no truncation
    # (the terminal's "up to 50" cap was for readability, not storage; this is
    # a structured, queryable column, so it keeps everything)
    problems: list = Field(default_factory=list, sa_column=Column(JSON))

class IngestRunCreate(SQLModel):
    project: str
    started_at: datetime
    status: str
    created: int
    updated: int
    unchanged: int
    problems: list = []

class IngestRunPublic(SQLModel):
    id: int
    project: str
    started_at: datetime
    finished_at: datetime
    status: str
    created: int
    updated: int
    unchanged: int
    problems: list

class Comment(SQLModel, table=True):
    """A remark attached to one entry — either preserved from the source
    XML's own editorial discussion (``oxy_comment_start``/``end`` PIs, plain
    ``<!-- -->`` comments) or written by a curator in the app. Deliberately
    **not** a `Relation`: a comment has free text, an author and a
    timestamp, and the same author may leave more than one, none of which
    fit `Relation`'s unique-triple shape.

    Never participates in `Entry.ingested_source_hash`/`_reconcile` — adding
    or ingesting a comment must never look like an edit to the entry's own
    fields (`Entry.updated_at` is untouched by anything here), and a source
    comment's text changing is a separate concern from the entry's data
    changing. See ``ingest._reconcile_comments``, keyed by
    ``(entry_id, author, created_at, text)``, not `_reconcile`.
    """

    __table_args__ = {"mysql_charset": "utf8mb4"}
    id: int | None = Field(default=None, primary_key=True)
    entry_id: int = Field(foreign_key="entry.id", index=True)
    text: str = Field(sa_column=Column(Text, nullable=False))
    author: str = Field(max_length=256)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    # "ingested" (from the source XML, author/created_at are the source
    # comment's own) | "app" (written by a curator, author/created_at are
    # the writing user's email and the write time)
    source: str = Field(max_length=16)
    # the data key(s) this comment is anchored to — equal = a clean
    # single-field comment; different = spans from start_field to end_field
    # (real source data does this, see docs/ingest/links-and-comments.md); both None = a
    # general, entry-level remark, not about any one field
    start_field: str | None = Field(default=None, max_length=128)
    end_field: str | None = Field(default=None, max_length=128)
    # raw mid/id/parentID attributes, verbatim, only ever set for an
    # ingested comment that was itself part of a source reply-thread — kept
    # so re-exporting an untouched ingested comment doesn't silently drop
    # its thread structure, even though the app itself doesn't expose
    # replying to a specific comment (see docs/ingest/links-and-comments.md)
    thread_meta: str | None = Field(default=None, max_length=512)

