class FieldSchema(SQLModel):
    """One form field. Not a table — part of the code-defined schema layer.

    ``repeatable`` fields hold a **list** in ``entry.data``; each item is an
    object ``{"value": ..., <qualifier>: ...}``. ``qualifier`` names that extra
    key (e.g. ``"lang"`` for multilingual names, ``"type"`` for typed ids) and
    ``qualifier_options`` are its suggested values. ``multiline`` marks long free
    text (a note, an Erläuterung): EntryDialog renders a full-width textarea and
    the entry table leaves the column out.
    """

    name: str
    label: str
    type: str  # text | number | select | checkbox | date | reference
    required: bool = False
    options: list[str] | None = None
    ref_type: str | None = None
    repeatable: bool = False
    qualifier: str | None = None
    qualifier_options: list[str] | None = None
    multiline: bool = False

class SchemaOverride(SQLModel):
    """Per-project delta applied on top of a base field list (see schemas._merge)."""

    add: list[FieldSchema] = []
    modify: dict[str, dict] = {}
    remove: list[str] = []
    order: list[str] | None = None
    # data keys a project's ingest profile legitimately writes but that are *not*
    # form fields: absent from resolve_schema()'s output and never rendered by
    # EntryDialog, but not drift either — schemas.validate_entry accepts them
    # instead of rejecting them as unknown. E.g. mop's `alt_names` (structured
    # name records, not a scalar the FieldSchema type system can express) and
    # avhr's `gnd`/`viaf`/`wikidata` (derived display views of `idno_other`,
    # deliberately not independently editable — see export.EXPORT["avhr"]).
    extra_keys: list[str] = []


class SourceState(SQLModel, table=True):
    """What the last ingest of a project read: the digest of its source files
    (``sources.digest``). The watcher ingests a project again only when the
    digest on the volume differs — and on the very first start, when there is
    no row yet."""

    __tablename__ = "source_state"
    __table_args__ = {"mysql_charset": "utf8mb4"}
    project: str = Field(foreign_key="project.name", primary_key=True, max_length=128)
    digest: str = Field(max_length=64)
    ingested_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


FILE_EVENTS = ("created", "modified", "moved", "deleted")


class FileNotice(SQLModel, table=True):
    """One file change ediarum.webdav reported (``POST /files``), kept until the
    watcher has seen it on the shared volume and ingested the project."""

    __tablename__ = "file_notice"
    __table_args__ = {"mysql_charset": "utf8mb4"}
    id: int | None = Field(default=None, primary_key=True)
    project: str = Field(foreign_key="project.name", max_length=128, index=True)
    event: str = Field(max_length=16)  # one of FILE_EVENTS
    path: str = Field(max_length=1024)  # relative to the project's checkout
    previous_path: str | None = Field(default=None, max_length=1024)  # "moved" only
    commit: str = Field(max_length=64)
    sha256: str | None = Field(default=None, max_length=64)  # of the posted content, if any
    received_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class FileNoticeOut(SQLModel):
    project: str
    event: str
    path: str
    commit: str
    queued: bool  # False: not a file this project's registers are read from
