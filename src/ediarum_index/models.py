class EntryBase(SQLModel):
    project_name: str = Field(foreign_key="project.name", max_length=128, index=True)
    entry_type: str = Field(foreign_key="entry_type.name", max_length=32, index=True)
    label: str = Field(max_length=512, index=True)
    # this entry's identifier in its originating source (e.g. a TEI `xml:id`);
    # not a foreign key or a reference to `project` — see docs/concepts/schema.md
    source_id: str | None = Field(default=None, max_length=255, index=True)

class Entry(EntryBase, table=True):
    __table_args__ = {"mysql_charset": "utf8mb4"}
    id: int | None = Field(default=None, primary_key=True)
    data: dict = Field(default_factory=dict, sa_column=Column(JSON))
    # integer sort keys derived from the (free-text) date fields by ``dates.sorts_for``
    # on every write; NULL when the value is missing or unparseable. Not in the
    # API models — internal, only used by ``?sort_by=birth_date`` / ``death_date``.
    birth_sort: int | None = Field(default=None, index=True)
    death_sort: int | None = Field(default=None, index=True)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime | None = None
    # Set together, server-side only, whenever a write supplies `ingested_source_hash`
    # (see EntryCreate / EntryUpdate) — never by a hand-entered or UI-edited write.
    # `ingested_source_hash` is a content hash of `data` as of that ingest run;
    # `ingested_at` is when it was written. Comparing the two against `updated_at`
    # on the next ingest run (ingest.py's `_reconcile`) is how a re-ingest tells a
    # changed source record (hash differs) apart from one a curator has edited in
    # the app since (`updated_at` newer than `ingested_at`) without re-fetching or
    # re-parsing anything else.
    ingested_at: datetime | None = None
    ingested_source_hash: str | None = Field(default=None, max_length=64)
    # convenience navigation only; not included in EntryPublic, so not lazy-loaded
    # during response serialisation
    project: Project | None = Relationship()
    type_row: EntryTypeRow | None = Relationship()

