class Project(SQLModel, table=True):
    """A project namespace. ``entry.project_name`` points here.

    ``name`` is the platform's project slug. The rows mirror the platform's
    project registry (``bootstrap.sync_projects``); a project the registry no
    longer lists stays, inactive, with its entries.
    """

    __table_args__ = {"mysql_charset": "utf8mb4"}
    name: str = Field(primary_key=True, max_length=128)
    label: str = Field(max_length=256)
    description: str | None = Field(default=None, max_length=1024)
    is_active: bool = Field(default=True)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

class ProjectPublic(SQLModel):
    name: str                        # the platform slug — the `/{project}/…` path segment
    label: str                       # display name for the project picker
    description: str | None = None    # optional: tooltip / admin
    is_active: bool                   # let the UI grey out / filter retired projects
    # where this app takes the registers from (platform registry): "xml" — the TEI
    # files, edits here don't reach them; "app" — kept here. None: registry
    # unreachable right now
    index_source_of_truth: Literal["xml", "app"] | None = "xml"
    # the registers are ingested from the project's TEI files: xml-led *and* a
    # REGISTER_DIR in its module. True: edits made here don't reach those files
    # (the UI says so). None: registry unreachable right now
    registers_from_xml: bool | None = True
    # entries created without a source_id get one from ediarum.id (ID_URL is set)
    assigns_ids: bool = False

